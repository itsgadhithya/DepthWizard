def test_6_json_contract_keys_and_timings(sample_png_bytes):
    """
    6. Strict verification of all required top-level keys in JSON contract.
    """
    response = client.post(
        "/api/v1/process",
        files={"file": ("test.png", sample_png_bytes, "image/png")}
    )
    assert response.status_code == 200
    data = response.json()

    required_keys = [
        "request_id",
        "state",
        "relative_depth_available",
        "camera_model_available",
        "metric_depth_available",
        "georeferencing_available",
        "dsm_available",
        "validation_available",
        "model_name",
        "device_used",
        "total_time_ms",
        "timings_ms",
        "messages",
        "warnings",
        "metadata",
        "camera",
        "calibration",
        "validation",
        "artifacts"
    ]
    for key in required_keys:
        assert key in data, f"Missing required top-level key: {key}"

    # Verify timings structure
    timings = data["timings_ms"]
    for t_key in [
        "ingestion_ms",
        "metadata_extraction_ms",
        "depth_inference_ms",
        "camera_modeling_ms",
        "3d_reconstruction_ms",
        "metric_calibration_ms",
        "geospatial_and_dsm_ms"
    ]:
        assert t_key in timings, f"Missing timing key: {t_key}"
        assert isinstance(timings[t_key], (int, float))

    assert data["total_time_ms"] > 0


def test_7_artifact_accessibility(sample_jpeg_bytes):
    """
    7. Test downloading generated artifacts via the GET artifact endpoints.
    """
    proc_res = client.post(
        "/api/v1/process",
        files={"file": ("target.jpg", sample_jpeg_bytes, "image/jpeg")}
    )
    assert proc_res.status_code == 200
    data = proc_res.json()
    req_id = data["request_id"]
    artifacts = data["artifacts"]

    # Test downloading input image
    input_url = artifacts["input_image"]["download_url"]
    r_img = client.get(input_url)
    assert r_img.status_code == 200
    assert len(r_img.content) > 0

    # Test downloading relative depth npy array
    depth_url = artifacts["relative_depth"]["download_url"]
    r_depth = client.get(depth_url)
    assert r_depth.status_code == 200
    loaded_arr = np.load(io.BytesIO(r_depth.content))
    assert isinstance(loaded_arr, np.ndarray)
    assert loaded_arr.shape == (256, 256)

    # Test downloading 3D PLY mesh
    mesh_url = artifacts["3d_model"]["download_url"]
    r_mesh = client.get(mesh_url)
    assert r_mesh.status_code == 200
    assert r_mesh.content.startswith(b"ply") or b"element vertex" in r_mesh.content


