def test_3_standard_image_without_geospatial(sample_jpeg_bytes):
    """
    3. Test standard JPEG upload without geospatial metadata.
    Must return STATE_B, relative_depth_available=True, metric_depth_available=False,
    georeferencing_available=False, dsm_available=False.
    """
    response = client.post(
        "/api/v1/process",
        files={"file": ("aerial_photo.jpg", sample_jpeg_bytes, "image/jpeg")},
        data={"modulation_weight": 0.35, "z_exaggeration": 1.0}
    )
    assert response.status_code == 200
    data = response.json()

    # Verify state and availability flags
    assert data["state"] == "STATE_B"
    assert data["relative_depth_available"] is True
    assert data["camera_model_available"] is True
    assert data["metric_depth_available"] is False
    assert data["georeferencing_available"] is False
    assert data["dsm_available"] is False
    assert data["validation_available"] is False

    # Verify metadata
    assert data["metadata"]["image_width"] == 256
    assert data["metadata"]["image_height"] == 256
    assert data["metadata"]["format"] == "JPG"
    assert data["metadata"]["geospatial"] is None

    # Verify camera
    assert data["camera"]["estimated"] is True
    assert data["camera"]["fx"] is not None
    assert data["camera"]["cx"] == 128.0

    # Verify calibration
    assert data["calibration"]["calibrated"] is False
    assert data["calibration"]["method"] == "none"

    # Verify artifacts
    assert "input_image" in data["artifacts"]
    assert "relative_depth" in data["artifacts"]
    assert "relative_depth_colored" in data["artifacts"]
    assert "3d_model" in data["artifacts"]
    assert "dsm" not in data["artifacts"]  # No DSM for uncalibrated image


